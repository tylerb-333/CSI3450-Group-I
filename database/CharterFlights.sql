USE master;
GO

IF DB_ID('CharterFlights') IS NOT NULL
BEGIN
    ALTER DATABASE CharterFlights SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE CharterFlights;
END
GO
IF DB_ID('CharterFlights') IS NULL
    CREATE DATABASE CharterFlights;
GO

USE CharterFlights;
GO

CREATE TABLE AIRPORT (
    AIRPORT_ID    INT IDENTITY(1,1) PRIMARY KEY,
    ICAO_CODE     CHAR(4)       NOT NULL UNIQUE,
    IATA_CODE     CHAR(3)       NULL UNIQUE,
    NAME          VARCHAR(100)  NOT NULL,
    CITY          VARCHAR(60)   NOT NULL,
    COUNTRY       VARCHAR(60)   NOT NULL,
    LATITUDE      DECIMAL(9,6)  NOT NULL,
    LONGITUDE     DECIMAL(9,6)  NOT NULL
);

CREATE TABLE PASSENGER (
    PASSENGER_ID  INT IDENTITY(1,1) PRIMARY KEY,
    FIRST_NAME    VARCHAR(50)   NOT NULL,
    LAST_NAME     VARCHAR(50)   NOT NULL,
    EMAIL         VARCHAR(100)  NULL UNIQUE,
    PHONE         VARCHAR(20)   NULL
);

CREATE TABLE CREW (
    CREW_ID         INT IDENTITY(1,1) PRIMARY KEY,
    FIRST_NAME      VARCHAR(50)  NOT NULL,
    LAST_NAME       VARCHAR(50)  NOT NULL,
    LICENSE_NUMBER  VARCHAR(20)  NOT NULL UNIQUE,
    ROLE            VARCHAR(25)  NOT NULL
);

CREATE TABLE FLIGHT (
    FLIGHT_ID               INT IDENTITY(1,1) PRIMARY KEY,
    FLIGHT_NUMBER           VARCHAR(10)  NOT NULL UNIQUE,
    ORIGIN_AIRPORT_ID       INT          NOT NULL REFERENCES AIRPORT(AIRPORT_ID),
    DESTINATION_AIRPORT_ID  INT          NOT NULL REFERENCES AIRPORT(AIRPORT_ID),
    DEPARTURE_DATETIME      DATETIME2    NOT NULL,
    ARRIVAL_DATETIME        DATETIME2    NOT NULL,
    AIRCRAFT_TAIL_NUMBER    VARCHAR(10)  NOT NULL,
    AIRCRAFT_TYPE           VARCHAR(40)  NOT NULL,
    SEAT_CAPACITY           INT          NOT NULL,
    CONSTRAINT CK_FLIGHT_DIFF_AIRPORTS CHECK (DESTINATION_AIRPORT_ID <> ORIGIN_AIRPORT_ID),
    CONSTRAINT CK_FLIGHT_TIMES CHECK (ARRIVAL_DATETIME > DEPARTURE_DATETIME),
    CONSTRAINT CK_FLIGHT_CAPACITY CHECK (SEAT_CAPACITY > 0)
);

CREATE TABLE BOOKING (
    BOOKING_ID    INT IDENTITY(1,1) PRIMARY KEY,
    PASSENGER_ID  INT         NOT NULL REFERENCES PASSENGER(PASSENGER_ID),
    FLIGHT_ID     INT         NOT NULL REFERENCES FLIGHT(FLIGHT_ID),
    SEAT_NUMBER   VARCHAR(4)  NOT NULL,
    CONSTRAINT UQ_BOOKING_PASSENGER_FLIGHT UNIQUE (PASSENGER_ID, FLIGHT_ID),
    CONSTRAINT UQ_BOOKING_FLIGHT_SEAT UNIQUE (FLIGHT_ID, SEAT_NUMBER)
);

CREATE TABLE ASSIGNMENT (
    FLIGHT_ID  INT NOT NULL REFERENCES FLIGHT(FLIGHT_ID),
    CREW_ID    INT NOT NULL REFERENCES CREW(CREW_ID),
    CONSTRAINT PK_ASSIGNMENT PRIMARY KEY (FLIGHT_ID, CREW_ID)
);
GO
